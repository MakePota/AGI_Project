"""工具错误的分类。

一次工具调用有**四种**结局，不是两种。判据是**「谁来修」**：

1. 成功。
2. 明确失败（``ToolError``）——确定没有产生副作用，而且是**计划的问题**。
   重规划换一种做法也许能成，所以可以重试。
3. 前提条件不满足（``PreconditionError``）——确定没有产生副作用，但**重规划也修不好**。
   代理没开、登录过期都是这一类，只有人能修。
4. 结果不确定（``UncertainOutcomeError``）——可能已经产生了副作用，但无法确认。

第 3、4 种都必须单独存在，而且**都不能重试**。混进第 2 种，调用方就会自动重试：
重试一个结果未知的写操作会在真实世界里叠加动作；重试一个代理没开的任务只是白烧额度。
而且两者要求用户做的事**完全相反**——一个去**核实是否已生效**，一个去**修好环境再重来**。

这不是假想。2026-10-12 真实发生过：Steam 加购的点击**已经成功**，但紧接着的
购物车复核因网络中断而失败，工具把这次调用报成「失败」，planner 据此重新规划，
购物车里最后躺着 3 份同一个游戏。整条链路没有任何报错，只有一句看起来合理的失败文案。
"""

from __future__ import annotations


class ToolError(Exception):
    """工具执行失败，且**确定没有产生副作用**。调用方可以安全地重试。"""


class UncertainOutcomeError(ToolError):
    """工具可能已经产生了副作用，但无法确认。

    **调用方不得自动重试。** 唯一正确的处理是停下来，让人去核实真实世界的状态。
    """

    def __init__(self, message: str) -> None:
        super().__init__(
            f"{message}\n"
            "（这是一次**结果不确定**的调用：动作可能已经生效。不要重试，"
            "请先人工核实真实状态，确认后再决定下一步。）"
        )


class PreconditionError(ToolError):
    """确定没有产生副作用，而且**重试不会改善**：工具运行的前提条件不满足。

    典型场景：代理没开、登录态过期、网络不通。这几件事重规划一百次也修不好——
    只有人能修。所以不该进重规划，应当立刻停下告诉用户该做什么。

    与 ``UncertainOutcomeError`` 的区别是关键的一对：

    - ``UncertainOutcomeError``：**可能已经做了，不知道** → 停下，让人去核实。
    - ``PreconditionError``：**确定没做，但你自己修不了** → 停下，让人去修复环境。

    两者的共同点是都不该重试；差别在于要告诉用户去做的事完全不同。
    """


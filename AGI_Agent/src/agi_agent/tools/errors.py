"""工具错误的分类。

一次工具调用有**三种**结局，不是两种：

1. 成功
2. 明确失败——**确定没有产生副作用**
3. **结果不确定**——可能已经产生了副作用，但无法确认

第三种必须单独存在。把它并入「失败」，调用方就会自动重试；而重试一个结果未知的
写操作，等于在一个可能已经变化了的世界里再叠加一次动作。

这不是假想。2026-10-12 真实发生过：Steam 加购的点击**已经成功**，但紧接着的
购物车复核因网络中断而失败，工具把这次调用报成「失败」，planner 据此重新规划，
购物车里最后躺着 3 份同一个游戏。整条链路没有任何报错，只有一句看起来合理的失败文案。
"""

from __future__ import annotations


class ToolError(Exception):
    """工具执行失败，且**确定没有产生副作用**。调用方可以安全地重试。"""


class UncertainOutcomeError(ToolError):
    """工具可能已经产生了副作用，但无法确认。

    **调用方不得自动重试。** 唯一正确的处理是停下来，让人去核实真实世界的状态。
    """

    def __init__(self, message: str) -> None:
        super().__init__(
            f"{message}\n"
            "（这是一次**结果不确定**的调用：动作可能已经生效。不要重试，"
            "请先人工核实真实状态，确认后再决定下一步。）"
        )
